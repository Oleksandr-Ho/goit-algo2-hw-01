# ========================================
# Потрібно реалізувати функцію, яка знаходить максимальний та мінімальний елементи в масиві, використовуючи метод «розділяй і володарюй».

# Критерії прийняття завдання:
# - Функція приймає масив чисел довільної довжини.
# - Використано рекурсивний підхід.
# - Повертається кортеж значень (мінімум, максимум).
# - Складність алгоритму — O(n).

# ========================================

#***************Min and Max (Пошук мінімального та максимального елементів)********************
def find_min_max(arr, left=0, right=None):
    if right is None:
        right = len(arr) - 1  # Якщо правий індекс не задано, встановлюємо його на останній індекс масиву

    # Базовий випадок: якщо підмасив містить лише один елемент,
    # цей елемент є і мінімальним, і максимальним
    if left == right:
        return arr[left], arr[left]

    mid = (left + right) // 2  # Обчислюємо середній індекс для розділу масиву

    # Рекурсивно знаходимо мінімум і максимум для лівої частини
    min_left, max_left = find_min_max(arr, left, mid)
    # Рекурсивно знаходимо мінімум і максимум для правої частини
    min_right, max_right = find_min_max(arr, mid + 1, right)

    # Порівнюємо мінімальні значення з обох частин
    if min_left < min_right:
        overall_min = min_left
    else:
        overall_min = min_right

    # Порівнюємо максимальні значення з обох частин
    if max_left > max_right:
        overall_max = max_left
    else:
        overall_max = max_right

    # Повертаємо кортеж (мінімум, максимум)
    return overall_min, overall_max

# Приклад використання Min and Max:
arr_min_max = [3, 1, 4, 1, 5, 9, 2]
result_min_max = find_min_max(arr_min_max)
print("Min and Max:", result_min_max)  # Очікуваний результат: (1, 9)
