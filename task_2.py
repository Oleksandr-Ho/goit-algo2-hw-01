# Потрібно реалізувати алгоритм пошуку k-го найменшого елемента в несортованому масиві, 
# використовуючи принцип Quick Select.

# Умови виконання:

# - Функція має приймати масив чисел та число k.
# - Необхідно використати підхід з вибором опорного елемента pivot .
# - Масив не має бути повністю відсортований.
# - Очікувана складність в середньому випадку має складати O(n).

import random

#***************Quick Select (Пошук k-го найменшого елемента)********************
def partition(arr, left, right, pivot_index):
    """
    Функція partition:
    Опис алгоритму:
      - Використовує схему Ломуту для розділення масиву.
      - Обирає значення опорного елемента (pivot) за індексом pivot_index.
      - Поміщає опорний елемент в кінець підмасиву.
      - Ітерує елементи від left до right-1:
            Якщо елемент менший за pivot_value, обмінює його з елементом на store_index і збільшує store_index.
      - Після обходу обмінює опорний елемент (на позиції right) з елементом на store_index,
            що встановлює його на остаточне місце.
      - Повертає індекс, на якому знаходиться опорний елемент (store_index).

    Числовий приклад:
      Для масиву [7, 10, 4, 3, 20, 15] та pivot_index, наприклад, 2 (pivot_value = 4):
        - Після переміщення pivot в кінець: [7, 10, 3, 3, 20, 4] (це лише приклад порядку)
        - Елементи менші за 4 будуть переміщені вліво, а потім pivot (4) опиниться на своєму місці.
    """
    pivot_value = arr[pivot_index]
    # Переміщуємо опорний елемент в кінець підмасиву
    arr[pivot_index], arr[right] = arr[right], arr[pivot_index]
    store_index = left  # Індекс для зберігання елементів менших за pivot_value
    # Проходимо всі елементи від left до right-1
    for i in range(left, right):
        if arr[i] < pivot_value:
            arr[store_index], arr[i] = arr[i], arr[store_index]  # Обмін елементів
            store_index += 1  # Збільшуємо store_index
    # Переміщуємо опорний елемент у його остаточну позицію
    arr[store_index], arr[right] = arr[right], arr[store_index]
    return store_index

def quick_select(arr, left, right, k):
    """
    Quick Select (Пошук k-го найменшого елемента):
    Опис алгоритму:
      - Використовує принцип "розділяй і володарюй" з вибором опорного елемента (pivot).
      - Базовий випадок: якщо підмасив містить лише один елемент (left == right),
        повертається цей елемент.
      - Обирається випадковий pivot_index між left та right.
      - За допомогою partition масив розділяється так, що pivot знаходиться у своїй остаточній позиції.
      - Якщо pivot_index співпадає з k, повертається елемент arr[k] як k-й найменший.
      - Якщо k менше pivot_index, рекурсивно шукаємо в лівій частині.
      - Інакше, рекурсивно шукаємо в правій частині.
    
    Числовий приклад:
      Для масиву [7, 10, 4, 3, 20, 15] та k = 2 (0-індексація, тобто 3-й найменший елемент):
        - Відсортований масив буде: [3, 4, 7, 10, 15, 20].
        - 3-й найменший елемент (індекс 2) дорівнює 7.
    Складність алгоритму:
      - Очікувана складність у середньому: O(n)
    """
    if left == right:
        return arr[left]  # Базовий випадок: підмасив містить лише один елемент

    # Обираємо випадковий індекс опорного елемента між left та right
    pivot_index = random.randint(left, right)
    # Розділяємо масив і отримуємо остаточну позицію опорного елемента
    pivot_index = partition(arr, left, right, pivot_index)

    # Якщо pivot знаходиться на позиції k, повертаємо його значення
    if k == pivot_index:
        return arr[k]
    # Якщо k менше pivot_index, шукаємо в лівій частині
    elif k < pivot_index:
        return quick_select(arr, left, pivot_index - 1, k)
    # Інакше шукаємо в правій частині
    else:
        return quick_select(arr, pivot_index + 1, right, k)

def quick_select_wrapper(arr, k):
    """
    Обгортка для Quick Select:
    Приймає масив та число k (де k - індекс k-го найменшого елемента, 0-індексація),
    викликає функцію quick_select та повертає k-й найменший елемент.
    """
    if k < 0 or k >= len(arr):
        raise IndexError("k повинен бути в межах від 0 до len(arr)-1")
    return quick_select(arr, 0, len(arr) - 1, k)

# Приклад використання Quick Select:
arr_quickselect = [7, 10, 4, 3, 20, 15]
k = 2  # Шукаємо 3-й найменший елемент (0-індексація: k=2)
result = quick_select_wrapper(arr_quickselect.copy(), k)
print(f"Quick Select: k-й найменший елемент (k={k}) =", result)  # Очікуваний результат: 7
